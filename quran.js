const Q = (() => {
  const before = [0];
  SURAHS.forEach((s, i) => before.push(before[i] + s[1]));
  const abs = (s, a) => before[s - 1] + a;
  const juzAbs = JUZ_STARTS.map(([s, a]) => abs(s, a));
  const juzOf = n => juzAbs.filter(x => x <= n).length;
  return {
    TOTAL: before[114],
    abs, juzAbs,
    name: s => SURAHS[s - 1][0],
    count: s => SURAHS[s - 1][1],
    // الجزء (أو الأجزاء) التي تقع فيها الآيات
    juz(s, f, t) {
      const a = juzOf(abs(s, f)), b = juzOf(abs(s, t));
      return a === b ? [a] : Array.from({ length: b - a + 1 }, (_, i) => a + i);
    },
    juzText(s, f, t) {
      const j = Q.juz(s, f, t);
      return j.length === 1 ? `الجزء ${j[0]}` : `الأجزاء ${j[0]} – ${j[j.length - 1]}`;
    }
  };
})();
